export function getRecommendationReason(title: string, keyword: string) {
  return (
    reasons.get(title.trim()) ??
    (keyword === "userCustom"
      ? "입력한 키워드와 관련된 도서 목록에서 고른 책이에요."
      : `‘${keyword}’ 키워드에 맞춰 고른 책이에요.`)
  );
}

export function getRecommendationBookCode(cover: string) {
  return cover.match(
    /^https:\/\/image\.aladin\.co\.kr\/product\/\d+\/\d+\/cover\d+\/([a-z0-9]{10}|97[89]\d{10})_\d+\.[a-z]+$/i
  )?.[1];
}
